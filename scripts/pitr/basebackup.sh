#!/usr/bin/env bash
# Take a physical base backup for point-in-time recovery, and prune old ones.
#
# Runs INSIDE the db container (pg_basebackup needs a replication connection, which the
# official image only allows locally). Normally started with:
#   docker compose -f docker-compose.yml -f docker-compose.pitr.yml exec -T -u postgres db \
#     bash /pitr/basebackup.sh
#
# A base backup alone restores to the moment the backup ended. Combined with the archived
# write-ahead log (WAL) it restores to any moment after that, up to the last archived WAL.
#
# Environment: BASE_BACKUP_DIR (default /backups/base), BASE_KEEP (default 3, newest kept),
# WAL_ARCHIVE_DIR (default /wal_archive).
set -euo pipefail

dir="${BASE_BACKUP_DIR:-/backups/base}"
archive="${WAL_ARCHIVE_DIR:-/wal_archive}"
keep="${BASE_KEEP:-3}"
user="${PGUSER:-${POSTGRES_USER:-postgres}}"
case "$keep" in '' | *[!0-9]*) echo "error: BASE_KEEP must be a number" >&2; exit 2 ;; esac
[ "$keep" -ge 1 ] || { echo "error: BASE_KEEP must be at least 1" >&2; exit 2; }

umask 077
mkdir -p "$dir"
name="base-$(date -u +%Y%m%dT%H%M%SZ)"
partial="$dir/$name.partial"
trap 'rm -rf "$partial"' EXIT

started="$(date +%s)"
# -X stream: the WAL needed to make this backup consistent is copied into the backup itself.
pg_basebackup -h "${PGHOST:-127.0.0.1}" -U "$user" -D "$partial" -Fp -X stream -c fast -l "$name"
mv "$partial" "$dir/$name"
trap - EXIT
seconds="$(( $(date +%s) - started ))"
echo "base_backup=$dir/$name"
echo "base_backup_seconds=$seconds"
echo "base_backup_bytes=$(du -sb "$dir/$name" | cut -f1)"

# Keep only the newest BASE_KEEP base backups.
# shellcheck disable=SC2012  # names are generated by this script and contain no odd characters
for old in $(ls -1d "$dir"/base-* 2>/dev/null | sort | head -n "-$keep"); do
  rm -rf "$old"
  echo "pruned_base_backup=$old"
done

# Archived WAL older than the oldest kept base backup can never be needed again: remove it, or
# the archive grows forever. The oldest needed file is named in that backup's backup_label.
# shellcheck disable=SC2012
oldest="$(ls -1d "$dir"/base-* | sort | head -n 1)"
needed="$(sed -n 's/^START WAL LOCATION: .*(file \([0-9A-F]*\))$/\1/p' "$oldest/backup_label")"
if [ -n "$needed" ] && [ -d "$archive" ]; then
  pg_archivecleanup "$archive" "$needed"
  echo "wal_archive_pruned_before=$needed"
fi
